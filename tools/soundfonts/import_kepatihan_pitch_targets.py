#!/usr/bin/env python3
"""Read pitch labels for the existing TSI SFZ maps; emit a C++ header to stdout.

Encoded cents are baked sample transpositions relative to the __from_ source,
not deviations relative to the target-note token. Unknown or velocity-dependent
pitch mappings are deliberately omitted. Plain filenames need an exact matching
group/sample in the tuning report; their pitch name alone does not imply 0 cents.
"""
import argparse
import csv
import math
from pathlib import Path
import re


def midi(note):
    match = re.fullmatch(r"([A-G])([#b]?)(-?\d+)", note)
    if not match:
        raise ValueError(note)
    return (12 * (int(match[3]) + 1)
            + dict(C=0, D=2, E=4, F=5, G=7, A=9, B=11)[match[1]]
            + {"#": 1, "b": -1, "": 0}[match[2]])


def normalize(absolute_cents):
    # Keep exact +50-cent ties on the lower nominal pitch.
    pitch = math.ceil((absolute_cents - 50) / 100)
    return pitch, round(absolute_cents - pitch * 100, 6)


def filename_target(filename):
    match = re.fullmatch(
        r"\d+-\d+_([A-G][#b]?-?\d+)_([+-]?\d+(?:\.\d+)?)c__from_"
        r".+-ord-([A-G][#b]?-?\d+)-.+\.wav", filename)
    if not match:
        return None
    return normalize(midi(match[3]) * 100 + float(match[2]))


def read_map(path, report_rows):
    candidates = {}
    group = path.stem.removeprefix("AutoMap_").removesuffix("_chroma")
    report = {(r["group"], Path(r["out_path"]).name): r for r in report_rows}
    for line in path.read_text().splitlines():
        if not line.startswith("<region>"):
            continue
        values = dict(re.findall(r"(\w+)=([^\s]+)", line))
        key = int(values["key"])
        filename = Path(values["sample"]).name
        target = filename_target(filename)
        if target is None:
            row = report.get((group, filename))
            if row:
                target = normalize(midi(row["target_note"]) * 100 + float(row["target_cents"]))
        # The SF2 converter currently only preserves baked WAV pitch, not tune.
        if float(values.get("tune", 0)) != 0:
            target = None
        if not (path.parent / values["sample"]).is_file():
            target = None
        candidates.setdefault(key, set()).add(target)
    return [(key, *next(iter(targets))) for key, targets in sorted(candidates.items())
            if len(targets) == 1 and None not in targets]


def collect(volume):
    roots = [
        ("8", "med-diversity", volume / "Orchidea_Tuning_8_SLLSL/Tuning_8.1_SLLSL_MedDiversity_SFZ"),
        ("8", "max-uniformity", volume / "Orchidea_Tuning_8_SLLSL/Tuning_8.1_SLLSL_MaxUniformity_SFZ"),
        ("7", "max-diversity", volume / "Tuning_7_LSSSL/Tuning_7.1_LSSSL_MaxDiversity_SFZ"),
    ]
    result = []
    for family, tuning, root in roots:
        for folder, instrument in [("Rebab", "rebab"), ("Gender_Barung", "gender-barung")]:
            actual = root
            if family == "7" and instrument == "gender-barung":
                actual = volume / "Orchidea_Tuning_7_LSSSL/Tuning_7.1_LSSSL_MaxDiversity"
            report = actual / (folder + "_report.csv")
            with report.open() as stream:
                rows = list(csv.DictReader(stream))
            for variant, group in enumerate(["D3", "F3", "F#3", "A3"], 1):
                path = actual / folder / ("AutoMap_" + group + "_chroma.sfz")
                for key, pitch, cents in read_map(path, rows):
                    result.append((f"{instrument}-tuning-{family}-{variant}-{tuning}", key, pitch, cents))
    return result


def header(entries):
    lines = [
        "// SPDX-License-Identifier: GPL-3.0-only",
        "// Generated by tools/soundfonts/import_kepatihan_pitch_targets.py.",
        "// Pitch labels from mapped filenames or exactly matched tuning reports.",
        "// These are encoded tuning targets, not measured sample fundamentals.",
        "#pragma once", "", "namespace mu::notation {",
        "struct KepatihanPitchTarget { const char* instrument; int key; int pitch; double cents; };",
        "inline constexpr KepatihanPitchTarget KEPATIHAN_PITCH_TARGETS[] = {",
    ]
    lines.extend(f'    {{ "{instrument}", {key}, {pitch}, {cents:g} }},'
                 for instrument, key, pitch, cents in entries)
    return "\n".join(lines + ["};", "}", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--volume", type=Path, default=Path("/Volumes/MyPassport2"))
    args = parser.parse_args()
    print(header(collect(args.volume)), end="")
